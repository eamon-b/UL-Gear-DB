-- Users are keyed by lower-cased verified email, so Google and magic-link sign-in for
-- the same address reach the same account.
CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT,
  created INTEGER NOT NULL
);

-- Only the SHA-256 of the session token is stored.
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires INTEGER NOT NULL,
  created INTEGER NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX sessions_expires ON sessions(expires);

-- List ids are generated by the client, so they are unique per user only.
-- A tombstone (deleted = 1) keeps only id and deletion time (updated).
CREATE TABLE lists (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  id TEXT NOT NULL,
  name TEXT NOT NULL,
  items TEXT NOT NULL,
  summary TEXT,
  created INTEGER NOT NULL,
  updated INTEGER NOT NULL,
  deleted INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, id)
);

-- A snapshot (list_id NULL) holds its own content. A live link (list_id set) reads the
-- owner's list on every request. owner_id is NULL for anonymous snapshots.
CREATE TABLE shares (
  id TEXT PRIMARY KEY,
  owner_id TEXT REFERENCES users(id) ON DELETE CASCADE,
  list_id TEXT,
  name TEXT,
  items TEXT,
  summary TEXT,
  created INTEGER NOT NULL,
  updated INTEGER NOT NULL
);
CREATE INDEX shares_owner ON shares(owner_id);
CREATE UNIQUE INDEX shares_live ON shares(owner_id, list_id) WHERE list_id IS NOT NULL;

-- Magic-link tokens (hashed, single use, 15 min).
CREATE TABLE email_tokens (
  token_hash TEXT PRIMARY KEY,
  email TEXT NOT NULL,
  return_to TEXT NOT NULL,
  expires INTEGER NOT NULL
);

-- Google OAuth state + PKCE verifier (hashed state, single use, 10 min).
CREATE TABLE oauth_states (
  state_hash TEXT PRIMARY KEY,
  verifier TEXT NOT NULL,
  return_to TEXT NOT NULL,
  expires INTEGER NOT NULL
);

-- Fixed-window counters. key = hash(bucket + subject) + window number.
CREATE TABLE rate_limits (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  expires INTEGER NOT NULL
);
